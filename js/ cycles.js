//          *
//         ***
//        *****
//       *******
//      *********
//     ***********
//(Подсказка: в конце фигуры есть перенос строки \n, который тоже учитывается в тестах. В КОНЦЕ КАЖДОЙ СТРОКИ НЕТ ПРОБЕЛОВ, ТОЛЬКО ПЕРЕНОС)
//Это похоже на то, что было в одном из уроков недавно, но сложнее. Задача непростая для новичков, так что с первого раза может не получится.

const lines = 5;
let result = '';
// Решение
for (let i = 1; i <= lines + 1; i++) {
  // Этот цикл выполняется от 1 до lines + 1 (6) включительно, с шагом 1. В каждой итерации цикла переменная i увеличивается на 1, что позволяет нам создавать строки с увеличивающимся количеством звездочек.
  for (let j = 0; j < lines - i + 1; j++) {
    // Этот внутренний цикл выполняется от 0 до lines - i + 1 (5 - i + 1) включительно, с шагом 1. В каждой итерации цикла переменная j увеличивается на 1, что позволяет нам добавлять пробелы в начале каждой строки, чтобы создать эффект выравнивания звездочек по центру.
    result += ' '; // В каждой итерации внутреннего цикла мы добавляем пробел к результату, чтобы создать отступ перед звездочками. Количество пробелов уменьшается с каждой итерацией внешнего цикла, что позволяет создать эффект выравнивания звездочек по центру.
  }
  for (let k = 0; k < 2 * i - 1; k++) {
    // Этот внутренний цикл выполняется от 0 до 2 * i - 1 (2 * i - 1) включительно, с шагом 1. В каждой итерации цикла переменная k увеличивается на 1, что позволяет нам добавлять звездочки в каждой строке. Количество звездочек увеличивается с каждой итерацией внешнего цикла, что позволяет создать эффект пирамиды.
    result += '*'; // В каждой итерации внутреннего цикла мы добавляем звездочку к результату, чтобы создать строку из звездочек. Количество звездочек увеличивается с каждой итерацией внешнего цикла, что позволяет создать эффект пирамиды.
  }
  result += '\n'; // В каждой итерации внешнего цикла мы добавляем перенос строки к результату, чтобы каждая строка звездочек была на новой строке. Это позволяет создать эффект пирамиды, где каждая строка содержит количество звездочек, соответствующее номеру итерации внешнего цикла.
}
