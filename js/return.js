function getMathResult(base, times) {
  if (typeof times !== 'number' || times <= 0) {
    return base;
  }

  let result = '';

  for (let i = 1; i <= times; i++) {
    if (i === times) {
      result += base * i;
    } else {
      result += base * i + '---';
    }
  }

  return result;
}
