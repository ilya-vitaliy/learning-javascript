// Важно понимать, что после return нельзя делать перенос строки, так как он не будет выполняться или может сломатся.
// Если функция должна вернуть какой-то результат для дальнейшей работы, то пригодится ключевое слово return! И так же стоит не забывать, что
// бы закончить функцию можно просто написать это слово return, без указания какого-либо значения, тогда функция вернет undefined.

// Упражнение1

function sayHello(name) {
  return 'Привет,' + name + '!';
}
// В данном случае функция sayHello принимает аргумент name и возвращает строку, которая приветствует этого человека.
// Например, если мы вызовем sayHello('Маша'), то мы получим 'Привет, Маша!'. Использование return позволяет нам получить результат
//  работы функции и использовать его в дальнейшем коде.

// Упражнение2

function returnNeighboringNumbers(num) {
  return [num - 1, num, num + 1];
}

console.log(returnNeighboringNumbers(5)); // В данном случае функция returnNeighboringNumbers принимает число num и возвращает массив,
//  который содержит три числа: num - 1, num и num + 1. Например, если мы вызовем returnNeighboringNumbers(5), то мы получим [4, 5, 6].
//  Использование return позволяет нам получить результат работы функции в виде массива и использовать его в дальнейшем коде.

