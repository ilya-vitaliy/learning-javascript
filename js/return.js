//Про важность return

const usdCurr = 28;
const discount = 0.9;

function convert(amount, curr) {
  return curr * amount;
}

function promotion(result) {
  console.log(result * discount);
}

const res = convert(500, usdCurr);

promotion(res);

// В данном случае мы создали функцию convert, которая принимает два аргумента amount и curr и возвращает
//  результат умножения этих аргументов. Затем мы создали функцию promotion, которая принимает результат функции convert и умножает его
//  на discount, а затем выводит результат в консоль. Если бы мы не использовали return в функции convert, то мы не смогли бы получить
//  результат умножения и передать его в функцию promotion, что бы она могла его использовать. Поэтому использование return в функциях
// очень важно!

//Пример - где будет полезно использовать return

function test() {
  for (let i = 0; i < 5; i++) {
    console.log(i);
    if (i === 3) return;
  }
  console.log('Done');
}

test();

// На самом-то деле любая функция всегда что-то возвращает, даже если мы не используем return. Если в функции нет return,
// то она возвращает undefined. В данном случае, когда i достигает 3, функция test завершает свою работу и не выполняет код после цикла,
//  поэтому 'Done' не будет выведено в консоль. Если бы мы не использовали return, то функция продолжала бы выполняться и в итоге вывела бы
// 'Done' после цикла. Поэтому использование return позволяет нам контролировать поток выполнения функции и выходить из нее в нужный момент.

