'use strict';
// Функция - это наши действия в джава скрипте, то есть это кусок кода, который выполняет определенные действия.
let num = 20;

function showFirstMessage(text) {
  console.log(text);
  num = 10; // В данном случае мы изменили значение глобальной переменной num, так как не объявляли внутри функции новую переменную с помощью let или const,
  // а просто присвоили ей новое значение. Если бы мы объявли внутри функции новую переменную с помощью let или const,
  //  то она бы была локальной и не повлияла бы на глобальную переменную num.
}
//Если мы обьявляем переменную внутри функции, то снаружи она уже будет недоступна и мы получим ошибку!
//Когда такая переменная let или const объявлена внутри функции, то она называется локальной переменной, а если объявлена снаружи,
// то она называется глобальной переменной. Локальная переменная доступна только внутри функции, а глобальная перменная доступна везде.
showFirstMessage('Hello world!');
console.log(num);

