const usdCurr = 28;
const eurCurr = 32;

function convert(amount, curr) {
  console.log(curr * amount);
}
convert(500, usdCurr);
convert(500, eurCurr); // В данном случае мы создали два аргумента функции convert - amount и curr. Когда мы вызываем функцию convert,
// мы передаем ей два аргумента - 500 и usdCurr, а затем 500 и eurCurr. Функция convert умножает эти аргументы и выводит результат в консоль.
// Вот почему аргументы функций и их использование так полезны!

