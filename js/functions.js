// Класификация функций:
// 1. Function expression - это когда мы создаем функцию и присваиваем ее переменной. Например:
const logger = function () {
  console.log('Hello');
}; // В данном случае мы создали функцию и присвоили ее переменной logger. Теперь мы можем вызвать эту функцию через переменную logger.
logger();
// Мы не можем вызвать эту функцию до ее объявления, так как она не будет доступна до того момента, пока мы не присвоим ее переменной!
// Этим она и отличается от function declaration, которая доступна до своего объявления, так как она поднимается вверх своего контекста выполнения. Например:
console.log(calc(2, 3)); // В данном случае мы можем вызвать функцию calc до ее объявления, так как она поднимается вверх своего контекста выполнения.
function calc(a, b) {
  return a + b;
}
// Разговор о современном стандарте ES6 и выше - это стрелочная функция. Стрелочная функция - это более короткий синтаксис
