//Замыкание – это функция, которая запоминает свои внешние переменные и может получить к ним доступ. В некоторых языках это невозможно,
//  или функция должна быть написана специальным образом, чтобы получилось замыкание. Но, как было описано выше, в JavaScript,
//  все функции изначально являются замыканиями (есть только одно исключение, про которое будет рассказано в Синтаксис "new Function").

//Простыми словами
// Замыкание функции - это сама функция вместе со всеми внешними переменными, которые ей доступны.

function createCounter() {
  let count = 0;

  return function () {
    count++;
    return count; // В данном случае мы возвращаем функцию, которая увеличивает значение переменной count на единицу и возвращает ее. Эта функция является замыканием, так как она запоминает переменную count, которая находится в ее внешнем окружении.
  };
}

const counter = createCounter();

console.log(counter()); // 1
console.log(counter()); // 2
console.log(counter()); // 3

//Аргументы функций
//Функции это наши оформленные действия в скриптах
